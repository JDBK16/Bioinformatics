_BLOSUM62 = {
    (row_aa, col_aa): int(score)
    for row_aa, line in zip(_ALPHABET, _BLOSUM62_ROWS.strip().splitlines())
    for col_aa, score in zip(_ALPHABET, line.split())
}


def blosum_score(a: str, b: str) -> int:
    """Return the BLOSUM62 substitution score for two amino acids.

    Arguments are single-letter amino acid codes and are case-insensitive.
    Besides the 20 standard residues, the ambiguity codes B (Asx), Z (Glx)
    and X (any), and the stop symbol '*', are supported.

    >>> blosum_score("A", "A")
    4
    >>> blosum_score("W", "w")
    11
    >>> blosum_score("L", "D")
    -4

    Raises:
        ValueError: if either argument is not a single supported character.
    """
    for residue in (a, b):
        if not isinstance(residue, str) or len(residue) != 1:
            raise ValueError(f"Expected a single character, got {residue!r}")

    key = (a.upper(), b.upper())
    try:
        return _BLOSUM62[key]
    except KeyError:
        bad = [r for r in (a, b) if r.upper() not in _ALPHABET]
        raise ValueError(
            f"Unknown amino acid code(s): {', '.join(map(repr, bad))}"
        ) from None


